#import <Foundation/Foundation.h>
#import <AudioToolbox/AudioToolbox.h>
#include <limits.h>
#include <math.h>

int main(int argc, const char **argv) {
    @autoreleasepool {
        if (argc != 2) return 2;
        NSURL *url = [NSURL fileURLWithPath:@(argv[1])];
        AudioFileID file = NULL;
        OSStatus status = AudioFileOpenURL((__bridge CFURLRef)url, kAudioFileReadPermission, 0, &file);
        AudioStreamBasicDescription format = {0};
        AudioFilePacketTableInfo table = {0};
        UInt64 packets = 0;
        if (!status) {
            UInt32 size = sizeof(format);
            status = AudioFileGetProperty(file, kAudioFilePropertyDataFormat, &size, &format);
            size = sizeof(table);
            if (!status) status = AudioFileGetProperty(file, kAudioFilePropertyPacketTableInfo, &size, &table);
            size = sizeof(packets);
            if (!status) status = AudioFileGetProperty(file, kAudioFilePropertyAudioDataPacketCount, &size, &packets);
            AudioFileClose(file);
        }
        if (status || format.mFormatID != kAudioFormatMPEG4AAC ||
            (format.mFormatFlags && format.mFormatFlags != kMPEG4Object_AAC_LC) ||
            !isfinite(format.mSampleRate) || format.mSampleRate < 1 ||
            format.mSampleRate > INT_MAX / 1000 || format.mSampleRate != floor(format.mSampleRate) ||
            format.mChannelsPerFrame < 1 || format.mChannelsPerFrame > 2 ||
            !format.mFramesPerPacket || !packets || packets > UINT32_MAX / format.mFramesPerPacket ||
            table.mNumberValidFrames <= 0 || table.mPrimingFrames < 0 || table.mRemainderFrames < 0 ||
            (UInt64)table.mNumberValidFrames + table.mPrimingFrames + table.mRemainderFrames != packets * format.mFramesPerPacket) {
            fprintf(stderr, "Cannot measure soundtrack %s (status %d). Expected an AAC-LC M4A with valid gapless sample metadata.\n", argv[1], (int)status);
            return 1;
        }
        printf("/* Generated by audio-info on every build. Do not edit. */\n"
               "#ifndef COPLAND_SOUNDTRACK_AUDIO_H\n#define COPLAND_SOUNDTRACK_AUDIO_H\n"
               "#define COPLAND_SOUND_RATE %u\n"
               "#define COPLAND_SOUND_FRAMES %lld\n"
               "#define COPLAND_SOUND_DURATION ((double)COPLAND_SOUND_FRAMES / COPLAND_SOUND_RATE)\n"
               "#endif\n", (unsigned)format.mSampleRate, (long long)table.mNumberValidFrames);
        fprintf(stderr, "Soundtrack measured: %.9f s (%lld valid samples at %u Hz, %u channels).\n",
                table.mNumberValidFrames / format.mSampleRate, (long long)table.mNumberValidFrames,
                (unsigned)format.mSampleRate, (unsigned)format.mChannelsPerFrame);
        return ferror(stdout) ? 1 : 0;
    }
}
